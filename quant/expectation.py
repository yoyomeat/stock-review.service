"""
预期模块 v1.0 — 基于策略矩阵的次日市场预期

每种 (周期 × 风格 × 主线) 组合对应一段纯文字预期，
嵌入操作计划输出，告诉用户"明天大概率怎样走、怎么应对"。

调用接口：
    get_expectation(cycle_label, invest_style, has_mainline, **kwargs) → str

参数：
    cycle_label:  "上升期D1~D5" / "上升期D6+" / "下降期" / "冰点期" / "反弹确认期" / "确认震荡期" / "分歧日"
    invest_style: "主升" / "低迷" / "抱团" / "散乱"
    has_mainline: True / False
    kwargs:
        cycle_day: int  (上升期第几天)
        sent: int       (情绪评分)
        prof: int       (赚钱评分)
        divergence: bool (是否分歧日)
        prev_style: str (前日风格，分歧日用)
        tracker_state: str (CONFIRMED/CANDIDATE/DEGRADED/NONE)
        tracker_health: int (0-100)
        tracker_sector: str (追踪的主线板块名)
"""


def get_expectation(cycle_label, invest_style, has_mainline, **kwargs):
    """
    返回对应组合的预期文字。
    无匹配或矛盾组合返回通用提示。
    """
    # 标准化
    cl = (cycle_label or '').strip()
    ms = (invest_style or '').strip()
    ml = bool(has_mainline)

    # v5.5 tracker 状态优先覆盖
    tracker_state = kwargs.get('tracker_state', '')
    tracker_health = kwargs.get('tracker_health', 100)
    tracker_sector = kwargs.get('tracker_sector', '')
    if tracker_state == 'CANDIDATE':
        return _exp_mainline_tolerant(tracker_sector, tracker_health)

    # 特殊过渡态优先
    if '冰点' in cl:
        return _exp_ice()
    if '反弹确认' in cl:
        return _exp_bounce_confirm()
    if '震荡' in cl:
        return _exp_range(ms, ml)
    if '分歧' in cl:
        return _exp_divergence(kwargs.get('prev_style', ''))
    
    # 主线分歧/需强修复状态
    ml_status = kwargs.get('mainline_status', '')
    ml_name = kwargs.get('mainline_name', '')
    if ml_status == 'divergence':
        return _exp_mainline_divergence(ml_name)
    if ml_status == 'needs_repair':
        return _exp_mainline_needs_repair(ml_name)

    # 矛盾组合
    if ms == '散乱' and ml:
        return '散乱与有主线矛盾，系统异常，请检查风格判定。'

    # 查表
    key = _make_key(cl, ms, ml)
    result = _EXPECTATIONS.get(key)
    if result:
        return result

    # 次要忽略组合（极少出现，简短提示）
    _rare = {
        '上升·主升·无主线': '上升初期主升无主线极少出现，观察赚钱效应来源，等主线浮现。',
        '上升·抱团·无主线': '上升初期抱团无主线极少出现，暂不定义预期。',
        '上升D6+·主升·无主线': '大周期主升无主线极少出现，持续观察。',
    }
    return _rare.get(key, f'未覆盖组合：{cl} × {ms} × {"有" if ml else "无"}主线，请补充。')


def _make_key(cycle, style, mainline):
    """构建查询key"""
    # 简化周期标签
    if 'D6' in cycle:
        c = '上升D6+'
    elif '上升' in cycle:
        c = '上升'
    elif '下降' in cycle:
        c = '下降'
    else:
        c = cycle
    m = '有' if mainline else '无'
    return f'{c}·{style}·{m}主线'


